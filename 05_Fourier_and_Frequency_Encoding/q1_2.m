clear
tstart=0;
tend=1;
fs=100;
ts=1/fs;
T=(tend-tstart);
N=T/ts;
t=tstart:ts:tend-ts;
f=(-fs/2):(fs/N):(fs/2-fs/N);
x2=cos(30*pi*t+pi/4);
plot(t,x2);
%%%%%%%%
y2=fftshift(fft(x2));
out=y2/max(abs(y2));
figure
plot(f,abs(out));
%%%%%%%%
to1=1e-6;
out(abs(out)<to1)=0;
theta=angle(out);
figure
plot(f,theta/pi)
xlabel('Frequency(Hz)')
ylabel('Phase/\pi')
