clear
clc
t=0:0.01:1-0.01;
fc=5;
rou=2/(3e8);
td1=250*1000*rou;
td2=200*1000*rou;
fd1=0.3*180/3.6;
fd2=0.3*216/3.6;
re1=0.5*cos(2*pi*(5+fd1)*(t-td1));
re2=0.6*cos(2*pi*(5+fd2)*(t-td2));
re=re1+re2;
[R2,R1,V2,V1]=dist(re);
function [R1,R2,V1,V2]=dist(re)
fc=5;
rou=2/(3e8);
forieh=fftshift(fft(re));
half=forieh(52:100);
[~,I]=sort(half,'descend');
fnew1=I(1);
fnew2=I(2);
est_fd1=fnew1-fc;
est_fd2=fnew2-fc;
V1=(est_fd1/0.3)*3.6;
V2=(est_fd2/0.3)*3.6;
new_phi1=abs(angle(half(I(1))));
new_phi2=abs(angle(half(I(2))));
est_td1=new_phi1/(2*pi*fnew1);
est_td2=new_phi2/(2*pi*fnew2);
R1=est_td1/(rou*1000);
R2=est_td2/(rou*1000);
end